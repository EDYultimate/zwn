function rngDay([y, m, d1, d2, base]: [number, number, number, number, number]): [
  string,
  number
][] {
  const p = (n: number) => String(n).padStart(2, '0')
  return Array.from({ length: d2 - d1 + 1 }, (_, i) => [`${y}-${p(m)}-${p(d1 + i)}`, base + i]) as [
    string,
    number
  ][]
}

